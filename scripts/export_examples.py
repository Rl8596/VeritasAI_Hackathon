"""Export the example pictures shown in the demo app (app/examples/).

    python scripts/export_examples.py                 # children's test X-rays + non-X-ray "trap" pictures
    python scripts/export_examples.py --include-rsna  # also adult X-rays from the RSNA test split

What is exported
  - 3 normal + 3 pneumonia X-rays of children from the Kermany held-out test set (CC BY 4.0).
  - with --include-rsna: 2 normal + 2 lung-opacity X-rays of adults from our RSNA test split.
    OFF by default: only switch it on once we have confirmed that the RSNA terms allow
    showing the images publicly.
  - 2 generated pictures that are not X-rays, to show the "unlike my training data" warning.

The X-rays are drawn at random with a fixed seed from images no model was trained on.
They are NOT hand-picked to make a model look good. examples.json records the true
label, the source and the age (where known) of every picture; the app shows them.
"""
import argparse
import json
import sys
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from pneumoshift import config as C, data  # noqa: E402

DEFAULT_OUT = C.REPO_ROOT / "app" / "examples"
OUR_FILES = ("child_*.png", "adult_*.png", "not_an_xray_*.png", "examples.json")   # what a re-run may delete

KERMANY_SOURCE = ("Kermany et al. 2018, official test set: children aged 1 to 5, "
                  "Guangzhou Women and Children's Medical Center, China. Licence CC BY 4.0.")
RSNA_SOURCE = "RSNA Pneumonia Detection Challenge 2018 (chest X-rays from the NIH Clinical Center, USA), our test split."
TRAP_SOURCE = "Generated by scripts/export_examples.py. Not an X-ray."


def pick(meta, mask, n, rng, unique=None):
    """n random rows of meta[mask] (at most one per `unique` value), in a reproducible order."""
    pool = meta[mask]
    if unique:
        pool = pool.drop_duplicates(unique)
    assert len(pool) >= n, f"only {len(pool)} candidates for {n} examples"
    return pool.iloc[np.sort(rng.choice(len(pool), size=n, replace=False))]


def save_xray(arr, path):
    Image.fromarray(np.asarray(arr, dtype=np.uint8)).save(path, optimize=True)


def kermany_examples(out, rng, n_per_class=3):
    X, meta = data.load_kermany()
    test = (meta.split == "test").values
    entries = []
    for label, word in ((0, "normal"), (1, "pneumonia")):
        rows = pick(meta, test & (meta.label == label).values, n_per_class, rng, unique="patient_id")
        for k, row in enumerate(rows.itertuples(), 1):
            name = f"child_{word}_{k}.png"
            save_xray(X[row.idx], out / name)
            entries.append(dict(
                file=name, true_label=word, label=label, group="children", age=None, age_note="1 to 5 years",
                caption=f"Child, {word}", source=KERMANY_SOURCE,
                details=dict(dataset="kermany", original_file=row.filename, subtype=row.subtype, split="test")))
    return entries


def rsna_examples(out, rng, n_per_class=2):
    X, meta = data.load_rsna()
    test_adults = ((meta.split == "test") & meta.is_adult).values
    entries = []
    for cls, label, word in (("Normal", 0, "normal"), ("Lung Opacity", 1, "lung opacity")):
        rows = pick(meta, test_adults & (meta.cls == cls).values, n_per_class, rng, unique="patient_id")
        for k, row in enumerate(rows.itertuples(), 1):
            name = f"adult_{word.replace(' ', '_')}_{k}.png"
            save_xray(X[row.idx], out / name)
            entries.append(dict(
                file=name, true_label=word, label=label, group="adults", age=int(row.age), age_note=None,
                caption=f"Adult ({int(row.age)}), {word}", source=RSNA_SOURCE,
                details=dict(dataset="rsna", patient_id=row.patient_id, sex=row.sex, view=row.view, split="test")))
    return entries


def draw_landscape(size=(640, 480)) -> Image.Image:
    """A child's drawing of a house under the sun: colourful, obviously not an X-ray."""
    w, h = size
    yy = np.linspace(0, 1, h)[:, None, None]
    sky = (1 - yy) * np.array([70, 150, 235]) + yy * np.array([200, 228, 250])
    img = Image.fromarray(np.broadcast_to(sky, (h, w, 3)).astype(np.uint8))
    d = ImageDraw.Draw(img)
    d.ellipse([w * 0.72, h * 0.08, w * 0.90, h * 0.32], fill=(255, 210, 60))                 # sun
    for cx, cy, r in ((0.20, 0.20, 0.07), (0.28, 0.18, 0.09), (0.36, 0.21, 0.06)):          # cloud
        d.ellipse([w * (cx - r), h * (cy - r), w * (cx + r), h * (cy + r)], fill=(255, 255, 255))
    d.ellipse([-w * 0.3, h * 0.55, w * 0.7, h * 1.5], fill=(80, 170, 90))                    # hills
    d.ellipse([w * 0.35, h * 0.62, w * 1.4, h * 1.6], fill=(60, 150, 80))
    d.rectangle([w * 0.30, h * 0.52, w * 0.52, h * 0.78], fill=(205, 92, 72))                # house
    d.polygon([(w * 0.27, h * 0.52), (w * 0.41, h * 0.36), (w * 0.55, h * 0.52)], fill=(120, 60, 50))
    d.rectangle([w * 0.39, h * 0.64, w * 0.44, h * 0.78], fill=(90, 60, 40))
    d.rectangle([w * 0.33, h * 0.57, w * 0.37, h * 0.63], fill=(250, 240, 180))
    d.rectangle([w * 0.46, h * 0.57, w * 0.50, h * 0.63], fill=(250, 240, 180))
    d.rectangle([w * 0.69, h * 0.60, w * 0.71, h * 0.80], fill=(100, 70, 40))                # tree
    d.ellipse([w * 0.63, h * 0.44, w * 0.77, h * 0.66], fill=(40, 120, 60))
    return img


def draw_document(size=(600, 800), seed=0) -> Image.Image:
    """A page that looks like a scanned letter: the kind of file that gets uploaded by mistake."""
    w, h = size
    rng = np.random.default_rng(seed)
    img = Image.new("RGB", size, (250, 250, 247))
    d = ImageDraw.Draw(img)
    d.rectangle([50, 50, 230, 78], fill=(40, 70, 120))                                       # letterhead
    d.rectangle([50, 92, 330, 100], fill=(150, 150, 150))
    d.rectangle([390, 50, 550, 58], fill=(150, 150, 150))
    d.rectangle([390, 68, 520, 76], fill=(150, 150, 150))
    y = 160
    for paragraph in range(5):
        for line in range(int(rng.integers(3, 7))):
            x = 50
            while x < w - 90:
                word = int(rng.integers(22, 80))
                d.rectangle([x, y, min(x + word, w - 50), y + 7], fill=(70, 70, 70))
                x += word + 9
                if line == 0 and paragraph == 0 and x > 220:      # a short greeting line
                    break
            y += 19
        y += 20
        if y > h - 170:
            break
    d.line([50, h - 110, 250, h - 110], fill=(70, 70, 70), width=2)                          # signature line
    d.rectangle([50, h - 98, 190, h - 91], fill=(150, 150, 150))
    return img


def trap_examples(out):
    entries = []
    for name, img, caption in (("not_an_xray_drawing.png", draw_landscape(), "Not an X-ray (a drawing)"),
                               ("not_an_xray_document.png", draw_document(), "Not an X-ray (a letter)")):
        img.save(out / name, optimize=True)
        entries.append(dict(file=name, true_label="not an X-ray", label=None, group=None, age=None, age_note=None,
                            caption=caption, source=TRAP_SOURCE, details=dict(dataset="generated")))
    return entries


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--include-rsna", action="store_true",
                    help="also export adult X-rays from the RSNA test split (check the RSNA terms first)")
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    ap.add_argument("--seed", type=int, default=C.SEED)
    args = ap.parse_args()

    out = args.out
    out.mkdir(parents=True, exist_ok=True)
    for pattern in OUR_FILES:            # a re-run without --include-rsna must also remove the adult pictures
        for old in out.glob(pattern):
            old.unlink()

    rng = np.random.default_rng(args.seed)
    examples = kermany_examples(out, rng)
    if args.include_rsna:
        examples += rsna_examples(out, rng)
    examples += trap_examples(out)

    manifest = dict(
        note="Example pictures for the demo app, written by scripts/export_examples.py. X-rays are drawn at random "
             f"(seed {args.seed}) from held-out test images that no model was trained on; they are not hand-picked.",
        seed=args.seed, includes_rsna=bool(args.include_rsna), examples=examples)
    (out / "examples.json").write_text(json.dumps(manifest, indent=2) + "\n")

    print(f"Wrote {len(examples)} examples to {out}")
    for e in examples:
        print(f"  {e['file']:30s} true label: {e['true_label']:13s} {e['caption']}")
    if not args.include_rsna:
        print("Adult (RSNA) examples were NOT exported. Use --include-rsna once the RSNA terms are confirmed.")
